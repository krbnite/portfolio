#===================================================================
#' Compute aggreagted PPTV website numbers.
#' 
#' @param as_on_dt
#' 
#' @param day1
#' 
#' @param ExlWrongWay
#' 
#' @export
#$
# 2017-05-10:  
#    EXL had been doing this wrong for MONTHS.  I never made a
#    a script to check this because the data set is so small
#    and straightforward, I just assumed it was not high
#    priority.  
#  
#    Basically, they would get (recentDate, pageViews) right, but
#    (previousDate, pageViews) wrong.  Similarly, they got 
#    (previousDate, uniqueViews) right, but (recentDate, uniqueViews)
#    wrong.  I found out it was because they were using 
#    (recentDate, uniqueViews) for (previousDate, pageViews), and
#    (previousDate, pageViews) for (recentDate, uniqueViews). 
#
pptv.offshore.web = function(
    as_on_dt=Sys.Date(),
    day1="Monday",
    v2=TRUE
) {
    
    data =  pptv.query.web(as_on_dt, agg=TRUE, day1)
    
    week_data = data %>% 
        dplyr::arrange(dplyr::desc(Date)) %>% 
        dplyr::slice(2:6) %>% 
        tidyr::gather(type, value, 2:7) %>% 
        tidyr::separate(type, into=c("Device", "Type"), sep="_") %>% 
        tidyr::spread(Date,value) %>% 
        dplyr::select(2,1,7,6,5,4,3) %>% 
        dplyr::mutate(
            WoW = paste0(as.character(round(100 * (.[[3]]-.[[4]])/.[[4]])),"%"),
            idx = dplyr::recode(Device,Web=1,App=2,Total=3), 
            Device=ifelse(Device=="App", "Mobile", Device)
        ) 
    
    # We no longer report YTD as of mid-May 2017.
    #  -- to see it, set v2=FALSE
    YTD = data %>%
        dplyr::summarize(
            Web_PV=sum(Web_PV), Web_UV=sum(Web_UV), 
            App_PV=sum(App_PV), App_UV=sum(App_UV),
            Total_PV=sum(Total_PV), Total_UV=sum(Total_UV)
        ) %>% 
        tidyr::gather(type, YTD, 1:6)  %>% 
        tidyr::separate(type, into=c("Device","Type")) %>%
        dplyr::mutate(Device = ifelse(Device=="App", "Mobile", Device)) %>%
        dplyr::select(2,1,3)
    
    # JOIN
    output = week_data %>% 
        dplyr::inner_join(YTD, by=c("Type", "Device")) %>%
        dplyr::arrange(Type,idx) %>% 
        dplyr::mutate(
            avg = (.[[4]]+.[[5]]+.[[6]]+.[[7]])/4.0,
            delta = paste0(round(100*(.[[3]]-avg)/avg), "%")
        ) %>%
        dplyr::select(c(1:6,8,10,12)) 
    
    # Format numbers:  Add commas
    output[[3]] = formatC(output[[3]], format="d", big.mark=",")
    output[[4]] = formatC(output[[4]], format="d", big.mark=",")
    output[[5]] = formatC(output[[5]], format="d", big.mark=",")
    output[[6]] = formatC(output[[6]], format="d", big.mark=",")
    output[[8]] = formatC(output[[8]], format="d", big.mark=",")
    
    # Return
    if (v2==FALSE) 
        output %>% dplyr::select(c(YTD, 3, 4, WoW)) 
    else output %>% dplyr::select(-YTD) 
    
}
