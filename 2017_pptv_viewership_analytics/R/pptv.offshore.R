            mLast4Avg = (m1+m2+m3+m4)/4.0,
            mVsLast4  = round(100 * (totMin - mLast4Avg) / mLast4Avg),
            u1 = dplyr::lead(totUniq, 1, order_by=dplyr::desc(showTitle)),
            u2 = dplyr::lead(totUniq, 2, order_by=dplyr::desc(showTitle)),
            u3 = dplyr::lead(totUniq, 3, order_by=dplyr::desc(showTitle)),
            u4 = dplyr::lead(totUniq, 4, order_by=dplyr::desc(showTitle)),
            uLast4Avg = (u1+u2+u3+u4)/4.0,
            uVsLast4  = round(100 * (totUniq - uLast4Avg) / uLast4Avg),
            mpu1 = dplyr::lead(minsPerUniq, 1, order_by=dplyr::desc(showTitle)),
            mpu2 = dplyr::lead(minsPerUniq, 2, order_by=dplyr::desc(showTitle)),
            mpu3 = dplyr::lead(minsPerUniq, 3, order_by=dplyr::desc(showTitle)),
            mpu4 = dplyr::lead(minsPerUniq, 4, order_by=dplyr::desc(showTitle)),
            mpuLast4Avg = (mpu1 + mpu2 + mpu3 + mpu4)/4.0,
            mpuVsLast4  = round(100 * (minsPerUniq - mpuLast4Avg) / mpuLast4Avg),
            mpv1 = dplyr::lead(minsPerView, 1, order_by=dplyr::desc(showTitle)),
            mpv2 = dplyr::lead(minsPerView, 2, order_by=dplyr::desc(showTitle)),
            mpv3 = dplyr::lead(minsPerView, 3, order_by=dplyr::desc(showTitle)),
            mpv4 = dplyr::lead(minsPerView, 4, order_by=dplyr::desc(showTitle)),
            mpvLast4Avg = (mpv1+mpv2+mpv3+mpv4)/4.0,
            mpvVsLast4  = round(100 * (minsPerView - mpvLast4Avg) / mpvLast4Avg)
        ) %>%
        dplyr::select(-c(
            v1,v2,v3,v4,vLast4Avg,
            m1,m2,m3,m4, mLast4Avg,
            u1,u2,u3,u4,uLast4Avg,
            mpu1,mpu2,mpu3,mpu4,mpuLast4Avg,
            mpv1,mpv2,mpv3,mpv4,mpvLast4Avg
            )) %>%
        dplyr::slice(1:N) 
    
    #========================================================
    # Smackdown
    #========================================================
    output = pptv_data %>% 
        dplyr::filter(
            version=='Other', #chinaAirDate>'2017-01-20', 
            show == 'Smackdown') %>% 
        dplyr::mutate(
            year = lubridate::year(chinaAirDate),
            week = lubridate::week(chinaAirDate),
            wday = ifelse(show=='Mon Night Raw',  'Monday', 'Tuesday'),
            usAirDate = as.Date(paste(year,week,wday), format="%Y %U %A"),
            chinaAirDate = usAirDate + lubridate::days(1))  %>%
        dplyr::group_by(
            #usAirDate, chinaAirDate, show, showTitle)       %>% 
            showTitle)       %>% 
        dplyr::summarize(
            totView=sum(totView),
            totMin=round(sum(totMin)),
            totUniq=sum(totUniq),
            minsPerUniq = round(totMin/totUniq,1),
            minsPerView = round(totMin/totView,1)
            ) %>% 
        dplyr::arrange(desc(showTitle)) %>% 
        dplyr::ungroup() %>%
        dplyr::mutate(
            orderNum=2,
            v1 = dplyr::lead(totView, 1, order_by=dplyr::desc(showTitle)),
            v2 = dplyr::lead(totView, 2, order_by=dplyr::desc(showTitle)),
            v3 = dplyr::lead(totView, 3, order_by=dplyr::desc(showTitle)),
            v4 = dplyr::lead(totView, 4, order_by=dplyr::desc(showTitle)),
            vLast4Avg = (v1+v2+v3+v4)/4.0,
            vVsLast4  = round(100 * (totView - vLast4Avg) / vLast4Avg),
            m1 = dplyr::lead(totMin, 1, order_by=dplyr::desc(showTitle)),
