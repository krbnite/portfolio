#' 
#' Bla, bla
#' 
#' @param pptv_data
#' 
#' @param N
#' 
#' @param to_csv
#' 
#' @export
#$
pptv.offshore.topmatches = function(
    pptv_data,
    N=20,
    to_csv=FALSE
) {
    
    as_on_dt = max(pptv_data$dataDate + lubridate::days(1), na.rm=TRUE)
    file = paste0(as.character(as_on_dt),"__top",as.character(N),"sf.csv")
    
    topNsf = pptv_data %>% 
        dplyr::filter(version=="Cut", payment=="FREE", dataDate >= as_on_dt - lubridate::days(30)) %>% 
        dplyr::mutate(showTitle=stringr::str_extract(showTitle,"[0-9]+$")) %>%
        dplyr::group_by(game) %>% 
        dplyr::summarize(AirDate=max(usAirDate), Show=max(show), Episode=max(showTitle), 
                         Views=sum(totView), Hours=round(sum(totMin)/60.)) %>% 
        dplyr::select(Show, Episode, AirDate, Match=game, Views, Hours) %>% 
        dplyr::arrange(desc(Views)) %>% 
        dplyr::mutate(
            Views = formatC(Views, format="d", big.mark=","),
            Hours = formatC(Hours, format="d", big.mark=",")
            ) %>%
        dplyr::slice(1:N) 

    if (to_csv==TRUE) {
        con = file(file, open="w", encoding="UTF-8")
        write.csv(topNsf, file=con, fileEncoding="UTF-8")
        close(con)  # Excel still sees chars more bizarre than Chinese symbols
        return(as.data.frame(topNsf))
    } 
    return(as.data.frame(topNsf))
    # Use Google Translate for match names. 
    # Not always straightforward:  Wrestlers names are often translated
    #   phonetically, or with some word that is a synonym of their name, etc.
}




