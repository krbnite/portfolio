#' Generate numbers given in the report for Live+7, Full Episode 
#' 
#' This function returns the Live+7 unique viewer and minute counts which correspond
#' to the most recently aired Raw and Smackdown full-length episodes 
#' relative to the provided as_on_dt. Additionally, it returns the
#' "Vs 4-Week Avg" KPIs found in report generated by the offshore
#' EXL team:
#' 
#' COMPUTE TRAILING 4-WEEK AVERAGE
#' trlAvg = avg(cnt_1wkAgo, cnt_2wksAgo, cnt_3wksAgo, cnt_4wksAgo)
#' 
#' COMPUTE THE DELTA (PERCENT DIFF BETWEEN THIS WEEK AND TRLNG AVG )
#' thisWksCnt - trlAvg            
#' --------------------- * 100\%   
#' trlAvg                   
#' 
#' The script was designed (in conjunction with most of the pptvR package)
#' to reverse engineer the numbers given in the PPTV report generated by the 
#' offshore EXL team.  For as long as the offshore EXL team is in charge
#' of generating the report, this script serves as a double
#' check to ensure no copy-and-paste errors have made their 
#' way into the report, which has happened from time to time.
#' 
#' @param as_on_dt (character or Date)
#' User may provide any date in the form YYYY-MM-DD, 
#' however it will be converted to the nearest, 
#' previous as_on_dt for which PPTV provided a data 
#' set.
#'          
#' @param View (optional; {TRUE|FALSE} or {0|1})
#' By default (FALSE) data is returned to parent environment
#' (whether that is to a variable or to screen). By
#' flagging View (TRUE), the data is instead routed to 
#' View()
#' 
#' @return Live+7, Full Episode metrics and KPIs for
#' the Raw and Smackdown episodes aired most recently
#' relative to the user-provided as_on_dt.         
#' 
#' @examples 
#' data = pptv.offshore.lp7("2017-03-09")
#'          
#' @export        
pptv.offshore.lp7 = function(
    pptv_data, 
    View=FALSE, 
    uniques=FALSE
) {
  
  #-------------------------------------------
  #--------        Get Data       ------------
  #-------------------------------------------
  as_on_dt = as.Date(max(pptv_data$dataDate)) + lubridate::days(1)
  
  # [1] LIVE DATA IN MOST RECENT 5-WK WINDOW
  trlng = as.data.frame(pptv.lp7(pptv_data, trail=5, agg=1))
  
  # [2a] Include Totals in Data Set
  totals = trlng %>% 
      dplyr::group_by(
          usAirDate, chinaAirDate, show
          ) %>%
      dplyr::summarize(
          audio    ='All', 
          subtitle ='All',
          totUniq  = sum(totUniq), 
          totView  = sum(totView),
          totMin   = sum(totMin)
          ) %>%
      as.data.frame()
  # NOTE: converted to data.frame b/c rbind is weird
  #   w/ tibbles.  Might be something better than rbind.
  
  # [2a] Include English Totals in Data Set
  trlng = rbind(trlng, totals)
  eng   = trlng %>% 
      dplyr::filter(
          audio=='English'
          ) %>%
      dplyr::group_by(
          usAirDate, chinaAirDate, show
          ) %>%
      dplyr::summarize(
          audio    = 'English', 
          subtitle = 'All',
          totUniq  = sum(totUniq), 
          totView  = sum(totView),
          totMin   = sum(totMin)
      ) %>%
      as.data.frame()   # rbind is weird w/ tibbles
  
  
  # [3] MOST RECENT L+7 DATA
  trlng = rbind(trlng, eng)
  LP7  = trlng %>%
      dplyr::filter(
          chinaAirDate >= as_on_dt - lubridate::weeks(2),
          chinaAirDate < as_on_dt - lubridate::weeks(1))
  
  # [4] TRAILING 4-Wk AVERAGE (Non-Inclusive)
  trlngAvg = trlng %>%
      dplyr::filter(
          chinaAirDate <= as_on_dt - lubridate::weeks(2)
      ) %>% 
      dplyr::group_by(
          show, audio, subtitle
      ) %>%
      dplyr::summarize(
          usAirDate     = max(usAirDate) + lubridate::days(7),
          trlAvgTotUniq = mean(totUniq),
          trlAvgTotView = mean(totView),
          trlAvgTotMin  = mean(totMin))
  
  # [4] JOIN LP7 w/ Trailing Avgs
  #  -- Offshore team reports to nearest integer
  output = LP7 %>%
      dplyr::inner_join(
          trlngAvg,
          by=c("usAirDate","show","audio","subtitle")
          ) 
  
  if (uniques==FALSE) {
      output = output %>% dplyr::transmute(
          usAirDate, show, audio, subtitle, totView, totMin,
          totViewVs4WkAvg = round(100*(totView-trlAvgTotView)/trlAvgTotView),
          totMinVs4WkAvg  = round(100*(totMin-trlAvgTotMin)/trlAvgTotMin)) 
  } else {
      output = output %>% dplyr::transmute(
          usAirDate, show, audio, subtitle, totUniq, totView, totMin,
          totUniqVs4WkAvg = round(100*(totUniq-trlAvgTotUniq)/trlAvgTotUniq),
          totViewVs4WkAvg = round(100*(totView-trlAvgTotView)/trlAvgTotView),
          totMinVs4WkAvg  = round(100*(totMin-trlAvgTotMin)/trlAvgTotMin))
  }
  
  output = output %>%  dplyr::arrange(usAirDate, show, dplyr::desc(audio))
  
  # DONE
  if(View==FALSE) { return(output) } else { View(output) }
}  




