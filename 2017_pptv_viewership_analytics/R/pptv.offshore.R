    pptv_data,
    N=3,
    all_vars=FALSE
) {
    # Latest 4 Videos, Air Date, Debut, Debut+7, To Date
    # Raw, SD, NXT
    # Metrics: Views, Mins, Mins/View
    #========================================================
    # Raw
    #========================================================
    max_date = max(pptv_data$dataDate)
    output = pptv_data %>% 
        dplyr::filter(
            version=='Other',
            show %in% c("Mon Night Raw", "Smackdown", "NXT")
        ) %>%
        dplyr::mutate(
            debut_mins  = ifelse(dataDate==chinaAirDate, totMin, 0),
            debut_views = ifelse(dataDate==chinaAirDate, totView, 0),
            dp7_mins    = ifelse(dataDate<=chinaAirDate+lubridate::days(6), totMin, 0),
            dp7_views   = ifelse(dataDate<=chinaAirDate+lubridate::days(6), totView, 0),
            idx         = dplyr::recode(show, "Mon Night Raw"=0, "Smackdown"=1, "NXT"=2, .default=3),
            # Have to filter out takeovers from NXT...
            showTitle   = dplyr::recode(
                showTitle, "takeover"="nxt001", "takeover brooklyn"="nxt002", 
                .default=showTitle)
        ) %>%
        dplyr::group_by(show, showTitle) %>%
        dplyr::summarize(
            idx         = max(idx),
            # Have to use chinaAirDate-1 b/c the NXT clips have no 
            #   corresponding usAirDate value
            air_date    = min(chinaAirDate-lubridate::days(1)), 
            debut_views = sum(debut_views[dataDate==min(chinaAirDate)]),
            debut_mins  = sum(debut_mins[dataDate==min(chinaAirDate)]),
            debut_mpv   = round(debut_mins / debut_views, 2),
            dp7_views   = sum(dp7_views[dataDate<=min(chinaAirDate)+lubridate::days(6)]),
            dp7_mins    = sum(dp7_mins[dataDate<=min(chinaAirDate)+lubridate::days(6)]),
            dp7_mpv     = round(dp7_mins / dp7_views, 2),
            td_views    = sum(totView),
            td_mins     = sum(totMin),
            td_mpv      = round(td_mins / td_views, 2)
        ) %>%
        dplyr::top_n(4, wt=air_date) %>%
        dplyr::arrange(idx, desc(showTitle)) %>% 
        dplyr::ungroup() %>%
        dplyr::select(
            showTitle, air_date, 
            debut_views, debut_mins, debut_mpv, 
            dp7_views, dp7_mins, dp7_mpv, 
            td_views, td_mins, td_mpv)
        
    #=====================
    output
        
}



