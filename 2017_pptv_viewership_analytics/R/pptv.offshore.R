#  pptv.offshore.overview
#===================================================================
#  Created 2017-04-21 (Kevin Urban)
#===================================================================
#' Compute numbers for "Total Viewership" and "Live Viewership" presented
#' on last page of Offshore Report.
#' 
#' This function will give you the numbers for Raw, Smackdown, Other,
#' and Total.  
#' 
#' @param pptv_data
#' Must input a PPTV data set, e.g., pptv_data = pptv.excel(as_on_dt).
#' 
#' @param type (default: "Total")
#' Specify either "Total Viewership" or "Live Viewership".  Note that
#' this parameter is not case sensitive and only depends on the first
#' letter (e.g., "LIVE" and "l" will both yield numbers for "Live 
#' Viewership").
#' 
#' @param all_vars
#' Default=FALSE. If TRUE, returns uniques too.
#' 
#' @export
pptv.offshore.overview = function(
    pptv_data, 
    type="Total",
    all_vars=FALSE
) {
    
    as_on_dt = as.Date(max(pptv_data$dataDate)) + lubridate::days(1)
    type = substring(tolower(type), 1, 1) # "t" or "l"
    
    thisYear           = lubridate::year(as_on_dt)
    thisMonth          = lubridate::month(as_on_dt)
    oneMonthBack       = lubridate::month(as_on_dt - months(1))
    twoMonthsBack      = lubridate::month(as_on_dt - months(2))
    threeMonthsBack    = lubridate::month(as_on_dt - months(3))
    thisMonthDay1      = as.Date(paste(thisYear,thisMonth,1),      format="%Y %m %d")
    lastMonthDay1      = as.Date(paste(thisYear,oneMonthBack,1),   format="%Y %m %d")
    twoMonthsAgoDay1   = as.Date(paste(thisYear,twoMonthsBack,1),  format="%Y %m %d")
    threeMonthsAgoDay1 = as.Date(paste(thisYear,threeMonthsBack,1),format="%Y %m %d")
    
    if (type=="l") {
        pptv_data = pptv_data %>% dplyr::filter(type=="LIVE")
    }
    
    output = pptv_data %>% 
        dplyr::mutate(
            show = ifelse(show=='Smackdown*','Smackdown',show),
            show = ifelse(show!='Smackdown', ifelse(show!='Mon Night Raw','Other',show), show),
            show_order = ifelse(show=="Mon Night Raw", 0, 
                                ifelse(show=="Smackdown", 1, 2)),
            hours_MTD = ifelse(dataDate >= thisMonthDay1, totMin/60., 0),
            hours_lastMonth     = ifelse(dataDate >= lastMonthDay1 & dataDate < thisMonthDay1, totMin/60., 0),
            hours_twoMonthsAgo   = ifelse(dataDate >= twoMonthsAgoDay1 & dataDate < lastMonthDay1, totMin/60., 0),
            hours_threeMonthsAgo = ifelse(dataDate >= threeMonthsAgoDay1 & dataDate < twoMonthsAgoDay1, totMin/60., 0),
            uniqs_MTD = ifelse(dataDate >= thisMonthDay1, totUniq, 0),
            uniqs_lastMonth     = ifelse(dataDate >= lastMonthDay1 & dataDate < thisMonthDay1, totUniq, 0),
            uniqs_twoMonthsAgo   = ifelse(dataDate >= twoMonthsAgoDay1 & dataDate < lastMonthDay1, totUniq, 0),
            uniqs_threeMonthsAgo = ifelse(dataDate >= threeMonthsAgoDay1 & dataDate < twoMonthsAgoDay1, totUniq, 0),
            views_MTD = ifelse(dataDate >= thisMonthDay1, totView, 0),
            views_lastMonth     = ifelse(dataDate >= lastMonthDay1 & dataDate < thisMonthDay1, totView, 0),
            views_twoMonthsAgo   = ifelse(dataDate >= twoMonthsAgoDay1 & dataDate < lastMonthDay1, totView, 0),
            views_threeMonthsAgo = ifelse(dataDate >= threeMonthsAgoDay1 & dataDate < twoMonthsAgoDay1, totView, 0)
        ) %>%
        dplyr::group_by(show) %>% #, show_order) %>% 
        dplyr::summarize(
            show_order           = max(show_order),
            hours_MTD              = round(sum(hours_MTD)/1000),
            hours_lastMonth      = round(sum(hours_lastMonth)/1000),
            hours_twoMonthsAgo   = round(sum(hours_twoMonthsAgo)/1000),
            hours_threeMonthsAgo = round(sum(hours_threeMonthsAgo)/1000),
            hours_SinceLaunch    = round(sum(totMin/60.)/1000),
            uniqs_MTD            = round(sum(uniqs_MTD)/1000),
            uniqs_lastMonth      = round(sum(uniqs_lastMonth)/1000),
            uniqs_twoMonthsAgo   = round(sum(uniqs_twoMonthsAgo)/1000),
            uniqs_threeMonthsAgo = round(sum(uniqs_threeMonthsAgo)/1000),
            uniqs_SinceLaunch    = round(sum(totUniq)/1000),
            views_MTD            = round(sum(views_MTD)/1000),
            views_lastMonth      = round(sum(views_lastMonth)/1000),
            views_twoMonthsAgo   = round(sum(views_twoMonthsAgo)/1000),
            views_threeMonthsAgo = round(sum(views_threeMonthsAgo)/1000),
            views_SinceLaunch    = round(sum(totView)/1000)
        )  
    
    output = output %>% 
        dplyr::summarize(
            show="Total", 
            show_order=3,
            hours_MTD             = sum(hours_MTD), 
            hours_SinceLaunch     = sum(hours_SinceLaunch),
            hours_lastMonth       = sum(hours_lastMonth),
            hours_twoMonthsAgo    = sum(hours_twoMonthsAgo),
            hours_threeMonthsAgo  = sum(hours_threeMonthsAgo),
            uniqs_MTD             = sum(uniqs_MTD), 
            uniqs_SinceLaunch     = sum(uniqs_SinceLaunch),
            uniqs_lastMonth       = sum(uniqs_lastMonth),
            uniqs_twoMonthsAgo    = sum(uniqs_twoMonthsAgo),
            uniqs_threeMonthsAgo  = sum(uniqs_threeMonthsAgo),
            views_MTD             = sum(views_MTD), 
            views_SinceLaunch     = sum(views_SinceLaunch),
            views_lastMonth       = sum(views_lastMonth),
            views_twoMonthsAgo    = sum(views_twoMonthsAgo),
            views_threeMonthsAgo  = sum(views_threeMonthsAgo)
        ) %>%
        rbind(output) %>%
        dplyr::arrange(show_order)
    
    output = output %>% 
        tidyr::gather(Metric, Value, -show, -show_order) %>% 
        tidyr::separate(Metric,into=c("Metric", "Interval")) %>% 
        tidyr::spread(Interval, Value) %>% 
        dplyr::arrange(desc(Metric),show_order) %>% 
        dplyr::mutate(Vwrshp="Total") %>%
        dplyr::select(Vwrshp, show, Metric, MTD, lastMonth, twoMonthsAgo, threeMonthsAgo, SinceLaunch)
    # WTF did I intend w/ the Vwrship column?!?!
    
    colnames(output) = c("Viewership", "Show", "Metric", "MTD",
                       as.character(lubridate::month(oneMonthBack,lab=1)), 
                       as.character(lubridate::month(twoMonthsBack,lab=1)),
                       as.character(lubridate::month(threeMonthsBack,lab=1)),
                       "SinceLaunch")
    
    # OUTPUT
    if (all_vars==TRUE) {
        output
    } else {
        output %>% dplyr::slice(c(1:4,9:12))
    }
    
}




#===================================================================
#  pptv.offshore.shortform
#===================================================================
#' Return table of values as would be seen on Short Form page of
#' Offshore's PPTV report.
#' 
#' Bla, bla
#' 
#' @param pptv_data
#' 
#' @param N
#' 
#' @param v2
#' In mid-May 2017, we changed the format of this page quite a bit.
#' Set to FALSE to view old way of doing it.
#' 
#' @param all_vars
#' 
#' @export
pptv.offshore.shortform = function(
    pptv_data,
    N=3,
    v2=TRUE,
    all_vars=FALSE
) {
    if (v2==TRUE) {
        pptv.offshore.shortform.v2(pptv_data, N=N, all_vars=all_vars)
    } else {
        pptv.offshore.shortform.v1(pptv_data, N=N, all_vars=all_vars)
    }
}
pptv.offshore.shortform.v1 = function(
    pptv_data,
    N=3,
    all_vars=FALSE
) {
    #========================================================
    # Raw
    #========================================================
    output = pptv_data %>% 
        dplyr::filter(
            version=='Other', #chinaAirDate>'2017-01-20', 
            show == 'Mon Night Raw') %>% 
        dplyr::mutate(
            year = lubridate::year(chinaAirDate),
            week = lubridate::week(chinaAirDate),
            wday = ifelse(show=='Mon Night Raw',  'Monday', 'Tuesday'),
            usAirDate = as.Date(paste(year,week,wday), format="%Y %U %A"),
            chinaAirDate = usAirDate + lubridate::days(1))  %>%
        dplyr::group_by(
            #usAirDate, chinaAirDate, show, showTitle)       %>% 
            showTitle)       %>% 
        dplyr::summarize(
            totView = sum(totView),
            totMin  = round(sum(totMin)),
            totUniq = sum(totUniq),
            minsPerUniq = round(totMin/totUniq,1),
            minsPerView = round(totMin/totView,1)
            ) %>% 
        dplyr::arrange(dplyr::desc(showTitle)) %>% 
        dplyr::ungroup() %>%
        dplyr::mutate(
            orderNum=1,
            v1 = dplyr::lead(totView, 1, order_by=dplyr::desc(showTitle)),
            v2 = dplyr::lead(totView, 2, order_by=dplyr::desc(showTitle)),
            v3 = dplyr::lead(totView, 3, order_by=dplyr::desc(showTitle)),
            v4 = dplyr::lead(totView, 4, order_by=dplyr::desc(showTitle)),
            vLast4Avg = (v1+v2+v3+v4)/4.0,
            vVsLast4  = round(100 * (totView - vLast4Avg) / vLast4Avg),
            m1 = dplyr::lead(totMin, 1, order_by=dplyr::desc(showTitle)),
            m2 = dplyr::lead(totMin, 2, order_by=dplyr::desc(showTitle)),
