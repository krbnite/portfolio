#' Return table of values as would be seen in Offshore's PPTV report.
#' 
#' Bla, bla
#' 
#' @param pptv_data
#' 
#' @export
#$
pptv.offshore = function(
    pptv_data
) {
    print("Creating LIVE table...")
    live            = pptv.offshore.live(pptv_data)
    print("Creating LIVE+7 table...")
    lp7             = pptv.offshore.lp7(pptv_data)
    print("Creating  SHORTFORM table...")
    shortform       = pptv.offshore.shortform(pptv_data)
    print("Creating TOP20 table...")
    top20           = pptv.offshore.topmatches(pptv_data)
    print("Creating TOTALS OVERVIEW table...")
    total_overview  = pptv.offshore.overview(pptv_data)
    print("Creating LIVE OVERVIEW table...")
    live_overview   = pptv.offshore.overview(pptv_data, type="live")
    print("Creating WEB table...")
    web             = pptv.offshore.web()
    
    list(live=live, lp7=lp7, shortform=shortform, 
         top20=top20, total_overview=total_overview, 
         live_overview=live_overview, web=web)
    
}




